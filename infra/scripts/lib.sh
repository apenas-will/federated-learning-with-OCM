LOCAL_CONTROL_PORT="${LOCAL_CONTROL_PORT:-19093}"
write_flwr_config() {
  mkdir -p "$FLWR_HOME"
  cat > "$FLWR_HOME/config.toml" <<TOML
# Generated by infra/scripts/lib.sh (write_flwr_config).
[superlink]
default = "ocm"

# SuperLink on the OCM hub: flower-addon NodePort 30093, mapped to 127.0.0.1 by kind.
[superlink.ocm]
address = "127.0.0.1:30093"
root-certificates = "$FLWR_HOME/ca.crt"

# Local deployment without clusters (infra/scripts/local-federation.sh).
[superlink.local]
address = "127.0.0.1:$LOCAL_CONTROL_PORT"
insecure = true
TOML
}

# Submit the Flower app and wait for the run to finish. The log stream of
# `flwr run --stream` can end before the run does, so completion is checked
# with `flwr ls`; the full run log is saved with `flwr log --show` at the end.
flwr_run_and_wait() {  # flwr_run_and_wait <connection> <logfile> [run-config]
  local conn="$1" logf="$2" cfg="${3:-}" flwr="$ROOT/.venv/bin/flwr" run_id status=""
  local args=(run "$ROOT/app" "$conn" --stream)
  [ -n "$cfg" ] && args+=(--run-config "$cfg")
  "$flwr" "${args[@]}" 2>&1 | grep --line-buffered -v -E 'PullMessages|Loading weights' | tee "$logf" || true
  run_id=$(grep -o 'Successfully started run [0-9]*' "$logf" | awk '{print $4}' | tail -1)
  [ -n "$run_id" ] || die "flwr run did not start a run; see $logf"
  for _ in $(seq 1 720); do  # up to one hour
    status=$("$flwr" ls "$conn" --run-id "$run_id" --format json 2>/dev/null \
      | "$ROOT/.venv/bin/python" -c 'import json,sys; print(json.load(sys.stdin)["runs"][0]["status"])' 2>/dev/null || true)
    case "$status" in finished*) break ;; esac
    sleep 5
  done
  "$flwr" log "$run_id" "$conn" --show 2>/dev/null | grep -v -E 'PullMessages|Loading weights' > "${logf%.log}-full.log" || true
  info "Flower run $run_id: ${status:-unknown}"
  [ "$status" = "finished:completed" ] || die "Flower run $run_id ended as '${status:-unknown}'; see $logf"
}

wait_for() {  # wait_for <seconds> <description> <command...>
  local timeout="$1" what="$2"; shift 2
  local start; start=$(date +%s)
  until "$@" >/dev/null 2>&1; do
    if [ $(( $(date +%s) - start )) -ge "$timeout" ]; then die "timed out waiting for $what"; fi
    sleep 3
  done
}
