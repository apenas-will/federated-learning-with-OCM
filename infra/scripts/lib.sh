# Shared settings for the infra scripts. Sourced, not executed.
# Works on macOS (bash 3.2) and Linux.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
export PATH="$ROOT/bin:$PATH"

# --- container runtime -------------------------------------------------------
# Rootful Podman or Docker (Docker Engine on Linux is open source too).
# Default: docker when there is an NVIDIA GPU (GPUs in kind need Docker),
# otherwise podman if installed, otherwise docker.
if [ -z "${CONTAINER_TOOL:-}" ]; then
  if nvidia-smi >/dev/null 2>&1 && command -v docker >/dev/null 2>&1; then CONTAINER_TOOL=docker
  elif command -v podman >/dev/null 2>&1; then CONTAINER_TOOL=podman
  else CONTAINER_TOOL=docker; fi
fi
export CONTAINER_TOOL
if [ "$CONTAINER_TOOL" = "podman" ]; then
  export KIND_EXPERIMENTAL_PROVIDER=podman
else
  unset KIND_EXPERIMENTAL_PROVIDER
fi

# --- GPU ----------------------------------------------------------------------
# GPU=auto (default): give the branch clusters the host's NVIDIA GPU when
# nvidia-smi works and the runtime is Docker. GPU=1 forces it, GPU=0 disables it.
GPU="${GPU:-auto}"
gpu_enabled() {
  case "$GPU" in
    1|true|yes) return 0 ;;
    0|false|no) return 1 ;;
  esac
  [ "$CONTAINER_TOOL" = "docker" ] && nvidia-smi >/dev/null 2>&1
}
# PyTorch 2.14.1 ships CUDA 12.6 and 13.0 builds; CUDA 13 needs driver >= 580.
torch_index() {
  local cuda
  cuda=$(nvidia-smi 2>/dev/null | grep -o 'CUDA Version: [0-9]*' | awk '{print $3}' || true)
  if [ -z "$cuda" ]; then echo "https://download.pytorch.org/whl/cpu"
  elif [ "$cuda" -ge 13 ]; then echo "https://download.pytorch.org/whl/cu130"
  else echo "https://download.pytorch.org/whl/cu126"
  fi
}

